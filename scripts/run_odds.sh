# オッズ収集の起動/再開スクリプト。Claude Code のセッションから独立して走る。
# 何度実行しても安全：取得済みはスキップ、二重起動はガード。
#
# ============================ 停止中（2026-07-20） ============================
# boatrace.jp のサイトポリシー禁止事項5「大量の情報送受信及び大量のアクセス」に
# 該当するため、全件取得（168,561件）は中止した。Akamai Bot Manager も稼働中で、
# 遮断されると自宅IPごと飛ぶ（テレボートも同一ドメイン）。詳細は README.md §3。
#
# 下の --end 20260718 のまま実行すると残り163,000件の取得を再開してしまう。
# 再開するなら方針A（標本化・数千〜1.5万レース）に従い、対象を絞ってから。
# 併せて適応スロットル（429/503でレート低下）と UA への連絡先追加を入れること。
# ==========================================================================
cd "$(dirname "$0")/.."

cat >&2 <<'EOS'
オッズ収集は中断中です。このスクリプトは意図的に無効化してあります。

  理由 : boatrace.jp サイトポリシー禁止事項5「大量の情報送受信及び大量のアクセス」
         ＋ Akamai Bot Manager 稼働中（遮断は自宅IP単位、テレボートも同一ドメイン）
  詳細 : README.md §3「規約・法的制約」
  現状 : 5,311件 / 34日分 取得済み（20230701〜0803）

再開するには、方針A（標本化・数千〜1.5万レース）に沿って対象日を絞ったうえで、
下のブロックのコメントを外し --start/--end を書き換えてください。
全期間（--end 20260718）での実行は残り約163,000件を叩くため復活させないこと。
EOS
exit 1

